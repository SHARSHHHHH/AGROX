/** Look up a UI string. Falls back to English, then to the key itself. */
export function translate(lang: Lang, key: string): string {
  return UI[lang]?.[key] ?? UI.en[key] ?? key
}

/**
 * Translate a DATA VALUE coming from the backend (crop, disease, severity…).
 * Unknown values are returned unchanged, so a new pest name shows in English
 * rather than disappearing.
 */
export function translateValue(lang: Lang, value: string): string {
  if (!value) return value
  const table = VALUES[lang]
  if (!table) return value
  if (table[value]) return table[value]
  // Case-insensitive retry, so "Tomato" matches "tomato".
  const lower = value.toLowerCase()
  for (const k of Object.keys(table)) {
    if (k.toLowerCase() === lower) return table[k]
  }
  return value
}
