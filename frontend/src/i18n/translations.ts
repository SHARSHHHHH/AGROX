/**
 * Complete UI translation dictionary — English, Tamil, Hindi.
 *
 * TWO KINDS OF TEXT NEED TRANSLATING
 * ----------------------------------
 * 1. UI chrome — headings, buttons, labels. Fixed strings, translated here.
 * 2. DATA VALUES — crop names, disease names, severity levels, IPM tiers,
 *    status badges. These arrive from the backend in English, so they are
 *    translated in VALUES below and looked up with tv().
 *
 * Translating only the first kind leaves a Tamil page reading
 * "கடுமையான தன்மை: MODERATE", which is exactly the half-translated result
 * we are trying to avoid.
 *
 * MISSING KEYS fall back to English rather than showing a raw key, so a gap
 * degrades to readable text instead of "pest.severity.high".
 */

